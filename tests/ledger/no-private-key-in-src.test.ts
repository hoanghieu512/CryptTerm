import { createHash } from 'node:crypto';
import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { stripComments } from '../support/strip-comments';

// Test no_private_key_in_src (ledger-format Requirements 7.1, 7.2, 7.3, 7.4, example, one run).
//
// Key isolation (security.md rule 2): the Demo_Key private value and its file name must not be
// reachable from `src/`, `public/` or `dist/`, and `src/` has no signing path. Reading the key
// file in a TEST is allowed. The demo key is public by design, but the browser must still never
// carry it, because tamper mode may not be able to re-sign.
//
// Failure messages hold file paths and booleans only, never the key value.

const REPO_ROOT = fileURLToPath(new URL('../..', import.meta.url));
const KEY_DIR = join(REPO_ROOT, 'scripts', 'demo-key');
const KEY_FILE_NAME = 'DEMO_ONLY_core_ledger_key';
const KEY_FILE = join(KEY_DIR, `${KEY_FILE_NAME}.json`);
const README_FILE = join(KEY_DIR, 'README.md');
const SRC_DIR = join(REPO_ROOT, 'src');
const TRUSTED_KEYS_FILE = join(SRC_DIR, 'ledger', 'trusted-keys.ts');
const GENERATED_HEADER =
  /^(?:\/\/|\/\*)\s*GENERATED by scripts\/gen-samples\.ts\. DEMO public key only\. Do not edit\./;

interface KeyMaterial {
  readonly dBase64Url: string;
  readonly dHex: string;
  readonly dBytes: Buffer;
  readonly publicHex: string;
  readonly publicBytes: Buffer;
}

/** Reads the Demo_Key JWK. Throws a fixed message and never shows a value. */
function readKeyMaterial(): KeyMaterial {
  const parsed: unknown = JSON.parse(readFileSync(KEY_FILE, 'utf8'));
  if (typeof parsed !== 'object' || parsed === null) throw new Error('TEST KEY FILE NOT AN OBJECT');
  const jwk = parsed as Record<string, unknown>; // checked to be a non-null object just above
  const d = jwk['d'];
  const x = jwk['x'];
  if (typeof d !== 'string' || typeof x !== 'string') throw new Error('TEST KEY FILE LACKS d OR x');
  const dBytes = Buffer.from(d, 'base64url');
  const publicBytes = Buffer.from(x, 'base64url');
  if (dBytes.length !== 32 || publicBytes.length !== 32) throw new Error('TEST KEY FILE WRONG LENGTH');
  return { dBase64Url: d, dHex: dBytes.toString('hex'), dBytes, publicHex: publicBytes.toString('hex'), publicBytes };
}

/** Every regular file under `dir`, recursively. */
function listFiles(dir: string): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) out.push(...listFiles(full));
    else out.push(full);
  }
  return out;
}

function toRepoPath(file: string): string {
  return relative(REPO_ROOT, file);
}

const CODE_EXTENSIONS = /\.(?:ts|tsx|js|jsx|mjs|cjs)$/;

describe('no_private_key_in_src', () => {
  it('no_private_key_in_src: the key value and the key file name appear in no file under src/, public/ or dist/', () => {
    const key = readKeyMaterial();
    const roots = [SRC_DIR, join(REPO_ROOT, 'public'), join(REPO_ROOT, 'dist')].filter((dir) => existsSync(dir));
    expect(roots.includes(SRC_DIR)).toBe(true);

    const offenders: string[] = [];
    for (const root of roots) {
      for (const file of listFiles(root)) {
        const bytes = readFileSync(file);
        // latin1 keeps every byte one character, so ASCII needles are found in binary files too.
        const text = bytes.toString('latin1');
        const found =
          text.includes(key.dBase64Url) ||
          text.toLowerCase().includes(key.dHex) ||
          text.includes(KEY_FILE_NAME) ||
          bytes.includes(key.dBytes);
        if (found) offenders.push(toRepoPath(file));
      }
    }
    expect(offenders).toEqual([]);
  });

  it('no_private_key_in_src: src/ has no subtle.sign, generateKey, exportKey and no path into scripts/', () => {
    const offenders: string[] = [];
    const patterns: readonly { readonly name: string; readonly pattern: RegExp }[] = [
      { name: 'subtle.sign', pattern: /\bsubtle\s*\.\s*sign\b/ },
      { name: 'generateKey', pattern: /\bgenerateKey\b/ },
      { name: 'exportKey', pattern: /\bexportKey\b/ },
      { name: 'scripts/', pattern: /scripts\// },
    ];
    let scanned = 0;
    for (const file of listFiles(SRC_DIR)) {
      if (!CODE_EXTENSIONS.test(file)) continue;
      scanned += 1;
      const code = stripComments(readFileSync(file, 'utf8'));
      for (const { name, pattern } of patterns) {
        if (pattern.test(code)) offenders.push(`${toRepoPath(file)} ${name}`);
      }
    }
    expect(scanned).toBeGreaterThan(0);
    expect(offenders).toEqual([]);
  });

  it('no_private_key_in_src: scripts/demo-key/README.md says DEMO ONLY and public by design', () => {
    const readme = readFileSync(README_FILE, 'utf8');
    expect(readme.includes('DEMO ONLY')).toBe(true);
    expect(/public by design/i.test(readme)).toBe(true);
  });

  it('no_private_key_in_src: the Demo_Key file is an Ed25519 OKP JWK with a 32-byte d and x', () => {
    const jwk = JSON.parse(readFileSync(KEY_FILE, 'utf8')) as Record<string, unknown>; // read in a test, public by design
    expect(jwk['kty']).toBe('OKP');
    expect(jwk['crv']).toBe('Ed25519');
    expect(readKeyMaterial().dBytes.length).toBe(32);
  });

  it('no_private_key_in_src: trusted-keys.ts is generated, holds one DEMO- public key and no private material', () => {
    const key = readKeyMaterial();
    const text = readFileSync(TRUSTED_KEYS_FILE, 'utf8');

    expect(GENERATED_HEADER.test(text)).toBe(true);
    expect((text.match(/DEMO-/g) ?? []).length).toBe(1);

    const entries = [...text.matchAll(/['"](DEMO-[0-9a-f]{16})['"]\s*:\s*['"]([0-9a-f]{64})['"]/g)];
    expect(entries.length).toBe(1);
    const sourceKeyId = entries[0]?.[1] ?? '';
    const publicHex = entries[0]?.[2] ?? '';

    // The value is the public half of the key file, and the id is derived from it (design "Digest").
    expect(publicHex === key.publicHex).toBe(true);
    const expectedId = `DEMO-${createHash('sha256').update(key.publicBytes).digest('hex').slice(0, 16)}`;
    expect(sourceKeyId === expectedId).toBe(true);

    // No private material in the file.
    expect(text.includes(key.dBase64Url)).toBe(false);
    expect(text.toLowerCase().includes(key.dHex)).toBe(false);
  });
});
