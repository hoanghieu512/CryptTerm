import { mkdtempSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { IdentityError, generateIdentity, runCli } from '../../scripts/gen-circuit-identity';
import { CIRCUIT_VERSION, VK_BYTE_LENGTH, VK_HASH } from '../../src/zk/circuit-identity';
import { sha256Hex } from '../../src/zk/sha256';

// Feature: zk-core, Requirement 7. circuit_identity_reproducible, circuit_identity_missing_artifact.
// The script writes into temporary folders here and never touches the committed files.

const repo = (path: string): string => fileURLToPath(new URL(`../../${path}`, import.meta.url));
const ARTIFACT = repo('src/zk/artifacts/ledger_audit.json');
const META = repo('src/zk/artifacts/ledger_audit.meta.json');
const SRS_DIR = repo('src/zk/artifacts/srs');
const COMMITTED_VK = repo('src/zk/artifacts/ledger_audit.vk');
const COMMITTED_IDENTITY = repo('src/zk/circuit-identity.ts');
const SLOW_MS = 120_000;

const tempDir = (): string => mkdtempSync(join(tmpdir(), 'cryptterm-identity-'));
const defaults = (outDir: string) => ({ artifactPath: ARTIFACT, metaPath: META, srsDir: SRS_DIR, outDir });

const read = (path: string): Buffer => readFileSync(path);

describe('circuit_identity_reproducible', () => {
  it(
    'circuit_identity_reproducible: two runs are byte-identical and equal the committed files',
    async () => {
      const first = tempDir();
      const second = tempDir();
      const a = await generateIdentity(defaults(first));
      const b = await generateIdentity(defaults(second));
      expect(b).toStrictEqual(a);
      for (const name of ['ledger_audit.vk', 'circuit-identity.ts']) {
        expect(read(join(first, name)).equals(read(join(second, name)))).toBe(true);
      }
      expect(read(join(first, 'ledger_audit.vk')).equals(read(COMMITTED_VK))).toBe(true);
      expect(read(join(first, 'circuit-identity.ts')).equals(read(COMMITTED_IDENTITY))).toBe(true);
      expect(a.circuitVersion).toBe(CIRCUIT_VERSION);
      expect(a.vkHash).toBe(VK_HASH);
    },
    SLOW_MS,
  );
});

describe('circuit_identity_reproducible committed values', () => {
  it('circuit_identity_reproducible: CIRCUIT_VERSION, VK_HASH and the key file agree', async () => {
    const artifactSha = await sha256Hex(read(ARTIFACT));
    expect(CIRCUIT_VERSION).toBe(`nargo-1.0.0+${artifactSha.slice(0, 32)}`);
    expect(CIRCUIT_VERSION).toHaveLength(44);
    const vk = read(COMMITTED_VK);
    expect(VK_BYTE_LENGTH).toBe(3680);
    expect(vk.length).toBe(VK_BYTE_LENGTH);
    expect(await sha256Hex(vk)).toBe(VK_HASH);
    expect(VK_HASH).toMatch(/^[0-9a-f]{64}$/);
    const text = read(COMMITTED_IDENTITY).toString('utf8');
    expect(text.startsWith('// GENERATED by scripts/gen-circuit-identity.ts. Do not edit.')).toBe(true);
    expect(text.endsWith('\n')).toBe(true);
  });
});

const STDOUT_LINES: readonly RegExp[] = [
  /^WROTE ledger_audit\.vk$/,
  /^WROTE circuit-identity\.ts$/,
  /^CIRCUIT_VERSION nargo-1\.0\.0\+[0-9a-f]{32}$/,
  /^VK_HASH [0-9a-f]{64}$/,
];

describe('circuit_identity_reproducible output', () => {
  it(
    'circuit_identity_reproducible: stdout holds file names and the two public values only',
    async () => {
      const out: string[] = [];
      const err: string[] = [];
      const dir = tempDir();
      const status = await runCli(['--out', dir], { out: (l) => out.push(l), err: (l) => err.push(l) });
      expect(status).toBe(0);
      expect(err).toStrictEqual([]);
      expect(out).toHaveLength(STDOUT_LINES.length);
      out.forEach((line, i) => expect(line).toMatch(STDOUT_LINES[i] as RegExp));
      expect(readdirSync(dir).sort()).toStrictEqual(['circuit-identity.ts', 'ledger_audit.vk']);
    },
    SLOW_MS,
  );
});

type Options = ReturnType<typeof defaults>;

/** The step named by the error, or a marker when nothing or another error was thrown. */
async function failureStep(options: Options): Promise<string> {
  try {
    await generateIdentity(options);
    return 'NO ERROR';
  } catch (error) {
    return error instanceof IdentityError ? error.step : 'OTHER ERROR';
  }
}

/** A meta file in a fresh folder with the given text. */
function metaWith(text: string): string {
  const path = join(tempDir(), 'meta.json');
  writeFileSync(path, text);
  return path;
}

const GOOD_META_VERSION = 'nargo version = 1.0.0';

describe('circuit_identity_missing_artifact', () => {
  it('circuit_identity_missing_artifact: a missing or unreadable Artifact stops at ARTIFACT', async () => {
    const out = tempDir();
    const missing = { ...defaults(out), artifactPath: join(tempDir(), 'none.json') };
    expect(await failureStep(missing)).toBe('ARTIFACT');
    expect(await failureStep({ ...defaults(out), artifactPath: tempDir() })).toBe('ARTIFACT');
    expect(readdirSync(out)).toStrictEqual([]);
  });

  it('circuit_identity_missing_artifact: a bad meta file stops at META', async () => {
    const out = tempDir();
    const noFile = { ...defaults(out), metaPath: join(tempDir(), 'none.json') };
    expect(await failureStep(noFile)).toBe('META');
    expect(await failureStep({ ...defaults(out), metaPath: metaWith('{not json') })).toBe('META');
    const unparsable = JSON.stringify({ nargoVersion: 'v1', artifactSha256: '0'.repeat(64) });
    const badVersion = metaWith(unparsable);
    expect(await failureStep({ ...defaults(out), metaPath: badVersion })).toBe('META');
    expect(readdirSync(out)).toStrictEqual([]);
  });
});

describe('circuit_identity_missing_artifact later steps', () => {
  it('circuit_identity_missing_artifact: a stale meta hash stops at ARTIFACT HASH', async () => {
    const out = tempDir();
    const stale = JSON.stringify({ nargoVersion: GOOD_META_VERSION, artifactSha256: '0'.repeat(64) });
    expect(await failureStep({ ...defaults(out), metaPath: metaWith(stale) })).toBe('ARTIFACT HASH');
    expect(readdirSync(out)).toStrictEqual([]);
  });

  it('circuit_identity_missing_artifact: a missing SRS folder stops at SRS', async () => {
    const out = tempDir();
    expect(await failureStep({ ...defaults(out), srsDir: join(tempDir(), 'none') })).toBe('SRS');
    expect(readdirSync(out)).toStrictEqual([]);
  });

  it('circuit_identity_missing_artifact: the command line exits 1 with a fixed line', async () => {
    const out = tempDir();
    const lines: string[] = [];
    const missing = join(tempDir(), 'none.json');
    const io = { out: (l: string) => lines.push(`OUT ${l}`), err: (l: string) => lines.push(`ERR ${l}`) };
    expect(await runCli(['--out', out, '--artifact', missing], io)).toBe(1);
    expect(lines).toStrictEqual(['ERR CIRCUIT IDENTITY FAILED: ARTIFACT']);
    expect(readdirSync(out)).toStrictEqual([]);
  });
});
